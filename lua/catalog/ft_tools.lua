---Filetype to tools mapping consumed by
---[catalog.opts.handle_ft_event](lua://catalog.opts.handle_ft_event).
---
---Keys are Neovim filetypes. Each value maps a
---[catalog.tool_kind](lua://catalog.tool_kind) to a list of package names.
---Always using a list keeps the shape uniform whether a kind needs one package
---or several: for example JavaScript and TypeScript use
---`{ lsp = { "typescript-language-server", "eslint-lsp" } }`. Names must be
---resolvable by a registered provider (by default, `mason`).
---
---Filetype families that share the same tooling reference one entry in
---`groups`, so related tools are described once. The returned mapping and the
---groups are read-only: nothing mutates them after load.
